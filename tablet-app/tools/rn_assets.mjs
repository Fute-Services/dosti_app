// Copies optimized images into the RN app with Android-safe names and writes
// src/assets/images.ts (require map + pixel sizes). Also creates tiny blurred
// copies used as cheap "frosted glass" backgrounds.
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const [optRoot, appRoot] = process.argv.slice(2);
const manifest = JSON.parse(fs.readFileSync(path.join(optRoot, 'manifest.json'), 'utf8'));

const clean = (s) => s
  .replace(/\.jpg \((\d)\)/i, '')           // "CHARM_A.jpg (1).jpeg" -> "CHARM_A"
  .replace(/\.jpg$/i, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '_')
  .replace(/^_+|_+$/g, '');

const dirFor = (rel) => {
  const r = rel.toLowerCase();
  if (r.includes('new floor/') || r.includes('pridewinga_v03')) return 'floor';
  if (r.includes('new unit imges/') || r.includes('sideunit')) return 'unit';
  if (r.includes('inventory/building/new/')) return 'building';
  if (r.includes('inventory/')) return 'inventory';
  if (r.includes('location1/')) return 'location';
  if (r.includes('tie-up/')) return 'tieup';
  if (r.includes('clubhouseamenities/')) return 'clubhouse';
  if (r.includes('gallery/')) return 'gallery';
  if (r.includes('master/')) return 'master';
  return 'brand';
};

const lines = [];
const blurred = [];
for (const [orig, opt] of Object.entries(manifest)) {
  const ext = path.extname(opt);
  let base = clean(path.basename(opt, ext));
  base = base.replace(/^map_for_animation_/, 'map_').replace(/^typical_floor_plan_/, 'floor_').replace(/^1_bhk_unit_plan_/, 'unit_1bhk_');
  const dir = dirFor(orig);
  const key = `${dir}_${base}`;
  const dest = path.join(appRoot, 'assets', 'images', dir, base + ext);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(optRoot, opt), dest);
  const meta = await sharp(dest).metadata();
  lines.push({ key, file: `${dir}/${base}${ext}`, w: meta.width, h: meta.height, orig });
  if (['gallery', 'clubhouse'].includes(dir)) blurred.push({ key, dest, dir, base });
}

// Extra brand files that are not in the web manifest (e.g. the SVG logo rendered to PNG).
for (const [key, file] of [['brand_dosti_logo', 'brand/dosti_logo.png']]) {
  const meta = await sharp(path.join(appRoot, 'assets', 'images', file)).metadata();
  lines.push({ key, file, w: meta.width, h: meta.height, orig: file });
}

// 48px-wide copies: stretched full screen they read as a heavy blur, at almost no cost.
const blurLines = [];
for (const b of blurred) {
  const out = path.join(appRoot, 'assets', 'images', b.dir, `${b.base}_blur.jpg`);
  await sharp(b.dest).resize({ width: 48 }).blur(1.2).jpeg({ quality: 70 }).toFile(out);
  blurLines.push(`  ${b.key}: require('../../assets/images/${b.dir}/${b.base}_blur.jpg'),`);
}

lines.sort((a, b) => a.key.localeCompare(b.key));
const ts = `// AUTO-GENERATED by tools/rn_assets.mjs — do not edit by hand.
// Every bundled image with its pixel size (used for aspect ratios / SVG overlays).
/** A bundled asset: Metro resolves require('./x.png') to a numeric asset id. */
export type AssetSource = number;

export type ImageAsset = { source: AssetSource; width: number; height: number };

export const images = {
${lines.map((l) => `  ${l.key}: { source: require('../../assets/images/${l.file}'), width: ${l.w}, height: ${l.h} },`).join('\n')}
} satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof images;

// Tiny pre-blurred copies for frosted backgrounds behind galleries.
export const blurredImages: Partial<Record<ImageKey, AssetSource>> = {
${blurLines.join('\n')}
};
`;
fs.mkdirSync(path.join(appRoot, 'src', 'assets'), { recursive: true });
fs.writeFileSync(path.join(appRoot, 'src', 'assets', 'images.ts'), ts);
fs.writeFileSync(path.join(appRoot, 'tools-asset-map.json'), JSON.stringify(lines, null, 2));
console.log(`${lines.length} images, ${blurLines.length} blurred`);
